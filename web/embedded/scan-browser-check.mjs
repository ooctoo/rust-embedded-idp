import { chromium } from "../../scripts/n2-ci/node_modules/playwright/index.mjs";

const browser = await chromium.launch({ headless: true, executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" });
const page = await browser.newPage({ viewport: { width: 320, height: 900 } });
const errors = [];
page.on("pageerror", error => errors.push(error.message));
await page.goto("http://127.0.0.1:4187/embedded/scan-demo.html");
await page.getByRole("heading", { name: "A04-D browser fixture" }).waitFor();
await page.getByRole("button", { name: "Toggle client" }).click();
if (!await page.getByText(/Scan sign-in is unavailable/).isVisible()) throw new Error("missing-client state is not visible");
await page.getByRole("button", { name: "Toggle client" }).click();
const loadCount = Number(await page.getByTestId("load-count").textContent());
const lookupCount = Number(await page.getByTestId("lookup-count").textContent());
await page.getByRole("button", { name: "Read local recovery record" }).click();
await page.waitForFunction(previous => Number(document.querySelector("[data-testid=load-count]")?.textContent) > previous, loadCount);
if (Number(await page.getByTestId("lookup-count").textContent()) !== lookupCount) throw new Error("empty recovery action called lookup instead of load");
await page.getByRole("button", { name: "Simulate create reply loss" }).click();
await page.getByRole("button", { name: "Show device code" }).click();
await page.getByRole("button", { name: "Confirm", exact: true }).click();
await page.getByText(/The server response is unknown/).waitFor();
await page.getByRole("button", { name: "Check status" }).click();
await page.getByText(/The server has not found the original scan yet/).waitFor();
await page.getByRole("button", { name: "Retry original start" }).click();
await page.getByRole("button", { name: "Confirm", exact: true }).click();
await page.getByText("Waiting for phone scan").first().waitFor();
await page.getByRole("button", { name: "Receive pending session" }).waitFor({ state: "detached" });
await page.getByRole("button", { name: "Simulate phone approval" }).click();
await page.getByRole("button", { name: "Receive pending session" }).click();
await page.getByRole("button", { name: "Confirm", exact: true }).click();
await page.getByText(/A pending session cannot access business services/).waitFor();
if (await page.getByText(/Server acknowledged receipt/).count()) throw new Error("pending was presented as active");
await page.getByRole("button", { name: "Simulate ACK reply loss" }).click();
await page.getByRole("button", { name: "Confirm receipt and activate" }).click();
await page.getByRole("button", { name: "Confirm", exact: true }).click();
await page.getByText(/Receipt result unknown/).waitFor();
await page.getByRole("button", { name: "Recover original operation" }).click();
await page.getByText(/The server acknowledged receipt/).waitFor();
if (await page.getByText("Device display code").count()) throw new Error("issued code remained visible after delivery");
if (await page.getByText("Delivery created; recover it").count()) throw new Error("acknowledged delivery was shown as recoverable");
const bodyText = await page.locator("body").innerText();
for (const secret of ["access_token", "refresh_token", "receipt_nonce", "signature", "delivery_secret"]) if (bodyText.includes(secret)) throw new Error(`secret label leaked: ${secret}`);
const dimensions = await page.evaluate(() => ({ scroll: document.documentElement.scrollWidth, client: document.documentElement.clientWidth }));
if (dimensions.scroll > dimensions.client) throw new Error(`320px overflow: ${JSON.stringify(dimensions)}`);
await (await import("node:fs/promises")).mkdir("/private/tmp/idp-a04d-ui", { recursive: true });
await page.getByRole("button", { name: "Reset fixture" }).click();
await page.getByRole("button", { name: "Show device code" }).click();
await page.getByRole("button", { name: "Confirm", exact: true }).click();
await page.getByRole("button", { name: "Simulate close reply loss" }).click();
await page.getByRole("button", { name: "Cancel this scan sign-in" }).click();
await page.getByRole("button", { name: "Confirm", exact: true }).click();
await page.getByText(/The server response is unknown/).waitFor();
await page.getByRole("button", { name: "Retry cancellation" }).click();
await page.getByRole("button", { name: "Confirm", exact: true }).click();
await page.getByText(/The original scan operation is closed/).waitFor();
if (await page.getByRole("button", { name: "Check status" }).count()) throw new Error("closed flow showed an invalid status button");
await page.getByRole("button", { name: "Show device code" }).waitFor({ state: "detached" });
await page.screenshot({ path: "/private/tmp/idp-a04d-ui/320.png", fullPage: true });
await page.goto("http://127.0.0.1:4187/embedded/scan-demo.html?real-renderer");
await page.getByRole("button", { name: "Show device code" }).click();
await page.getByRole("button", { name: "Confirm", exact: true }).click();
await page.locator('[aria-label="Device display code"] svg path').first().waitFor();
await page.getByRole("button", { name: "Simulate phone approval" }).click();
await page.locator('[aria-label="Device display code"]').waitFor({ state: "detached" });
if (errors.length) throw new Error(errors.join("\n"));
await browser.close();
console.log("A04-D browser fixture passed (320px, pending/active distinction, no visible secret labels).");
